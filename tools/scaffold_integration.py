def main(argv: Sequence[str] | None = None) -> int:
    """Create an integration and print what still has to be written by hand."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("integration", help="the vendor name, lowercase with underscores")
    parser.add_argument(
        "--domain",
        required=True,
        help="the methodology domain this vendor's skill starts from",
    )
    parser.add_argument(
        "--dry-run", action="store_true", help="report what would be written without writing it"
    )
    arguments = parser.parse_args(argv)

    try:
        written = scaffold_integration(
            REPO_ROOT,
            arguments.integration,
            domain=arguments.domain,
            dry_run=arguments.dry_run,
        )
    except ScaffoldError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1

    verb = "would write" if arguments.dry_run else "wrote"
    for path in written:
        print(f"{verb} {path.relative_to(REPO_ROOT)}")

    if arguments.dry_run:
        return 0

    print("\nNo existing file was edited — discovery finds this on the next build.")
    print("Before it is worth shipping:")
    for index, step in enumerate(remaining_work(arguments.integration), 1):
        print(f"  {index}. {step}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
