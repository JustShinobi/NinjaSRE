"""Create an integration that is complete on the first commit (FR-017).

An integration has seven artefacts, and five of them are boring. The schema is
four fields, the client is a base class and two methods, the verifier is a probe
and a permission list, the documentation has three headings, and the scenario is
a scripted response. Written by hand, every one of them is a chance to write it
slightly differently from every other one — and the two that are not
boring, the methodology and the permission list, are the ones a contributor runs
out of energy for after writing the five that were.

So this writes all seven, none of them empty, and edits nothing. That second
half is what makes a catalogue of any size
addable one package at a time: discovery walks the tree, so there is no registry
to append to and no merge conflict on every pull request.

**What it deliberately does not decide.** The side-effect level has no default,
structurally, and this writes ``READ`` with the reasoning beside it rather than
silently. The permission list is a stub, because a permission somebody guessed
is worse than one nobody wrote — a verifier that probes the wrong scope reports
success for a credential that cannot do the job. Both are printed as follow-up
work, because a template with a marked field gets filled in and a field that was
never mentioned does not.

Usage::

    python tools/scaffold_integration.py <vendor> --domain <domain> [--dry-run]
"""

