def _titled(name: str) -> str:
    """Return ``name`` as a human-readable display name."""
    return name.replace("_", " ").title()


def _class_prefix(name: str) -> str:
    """Return ``name`` as a class-name prefix."""
    return "".join(part.capitalize() for part in name.split("_"))


def _write(path: Path, text: str) -> None:
    """Write ``text`` to ``path``, creating the directories above it."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def _skill_from_template(repo_root: Path, integration: str, domain: str) -> str:
    """Return the domain template with the vendor substituted in (FR-018)."""
    source = repo_root.joinpath(*_TEMPLATE_ROOT_PARTS, template_for(domain), "SKILL.md")
    return source.read_text(encoding="utf-8").replace(PLACEHOLDER, integration)


def scaffold_integration(
    repo_root: Path,
    integration: str,
    *,
    domain: str,
    dry_run: bool = False,
) -> list[Path]:
    """Create the integration's seven artefacts and return the paths written."""
    plan = validate(repo_root, integration, domain)
    written = list(plan.paths())
    if dry_run:
        return written

    fields = {
        "integration": integration,
        "title": _titled(integration),
        "domain": domain,
        "category": _CATEGORY_MEMBERS[domain],
        "client_class": f"{_class_prefix(integration)}Client",
        "verifier_class": f"{_class_prefix(integration)}Verifier",
        "provenance": _PROVENANCE,
    }

    _write(plan.schema, SCHEMA_TEMPLATE.format(**fields))
    _write(plan.client, CLIENT_TEMPLATE.format(**fields))
    _write(plan.verifier, VERIFIER_TEMPLATE.format(**fields))
    _write(plan.tools_package / "__init__.py", TOOLS_PACKAGE_TEMPLATE.format(**fields))
    _write(plan.tool_module, TOOL_TEMPLATE.format(**fields))
    _write(plan.package / "__init__.py", PACKAGE_TEMPLATE.format(**fields))
    _write(plan.docs, DOCS_TEMPLATE.format(**fields))
    _write(plan.skill, _skill_from_template(repo_root, integration, domain))
    _write(plan.scenario, SCENARIO_TEMPLATE.format(**fields))

    return written


