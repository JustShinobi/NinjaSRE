class ScaffoldError(Exception):
    """The integration cannot be created as asked."""


@dataclass(frozen=True)
class Plan:
    """Where a scaffolded integration's seven artefacts go."""

    package: Path
    schema: Path
    verifier: Path
    client: Path
    tools_package: Path
    tool_module: Path
    docs: Path
    skill: Path
    scenario: Path

    def paths(self) -> tuple[Path, ...]:
        """Return every path this plan writes, in the order it writes them."""
        return (
            self.package / "__init__.py",
            self.schema,
            self.client,
            self.verifier,
            self.tools_package / "__init__.py",
            self.tool_module,
            self.docs,
            self.skill,
            self.scenario,
        )


def template_for(domain: str) -> str:
    """Return the template directory a domain's skill starts from.

    Identity, and that is the design: the template directories are named for the
    catalogue's category values, so there is no mapping table to keep in step
    with the enum. A domain with no directory is caught by ``validate``.
    """
    return domain


def domains(repo_root: Path) -> tuple[str, ...]:
    """Return every domain a skill can be started from, in name order."""
    root = repo_root.joinpath(*_TEMPLATE_ROOT_PARTS)
    if not root.is_dir():
        return ()
    return tuple(sorted(path.parent.name for path in root.rglob("SKILL.md")))


def plan_for(repo_root: Path, integration: str) -> Plan:
    """Return where the seven artefacts go for ``integration``."""
    package = repo_root / "integrations" / integration
    return Plan(
        package=package,
        schema=package / "schema.py",
        verifier=package / "verifier.py",
        client=package / "client.py",
        tools_package=package / "tools",
        tool_module=package / "tools" / "log_statistics.py",
        docs=package / "docs.md",
        skill=repo_root.joinpath(*_SKILL_ROOT_PARTS) / integration / "SKILL.md",
        scenario=repo_root.joinpath(*_SCENARIO_ROOT_PARTS) / f"{integration}.py",
    )


def validate(repo_root: Path, integration: str, domain: str) -> Plan:
    """Return the plan, or explain why the integration cannot be created."""
    if integration.startswith("_"):
        raise ScaffoldError(
            f"{integration!r} begins with an underscore, which marks a framework package "
            f"under integrations/ — discovery skips those, so the integration would be "
            f"invisible the moment it landed"
        )
    if not INTEGRATION_NAME_PATTERN.match(integration):
        raise ScaffoldError(
            f"{integration!r} is not a usable integration name: lowercase, starting with a "
            f"letter, letters, digits, and underscores only. It becomes a package name and "
            f"the prefix of every tool name the model emits as a symbol."
        )

    available = domains(repo_root)
    if domain not in available:
        raise ScaffoldError(
            f"{domain!r} is not a domain with a methodology template. Available: "
            f"{', '.join(available) if available else 'none'}"
        )

    plan = plan_for(repo_root, integration)
    for path in plan.paths():
        if path.exists():
            raise ScaffoldError(f"{path.relative_to(repo_root)} already exists")
    return plan


