"""Application-wide constants, re-exported from their owning domain module.

Every bound, environment-variable name, and shared literal in NinjaSRE lives
under this package (Constitution Article II, clause 6, and FR-009). A magic
number or a bare env-var string at a call site is a defect, and
``tools/check_constants.py`` fails the build on one.

Import from the domain module when you want the context that comes with it::

    from config.constants.investigation import MAX_INVESTIGATION_LOOPS

Import from here when you want several unrelated constants at once. Both reach
the same object; this module adds no behaviour of its own.
"""

