"""The credential a fresh deployment gives its operator, and how it stops existing.

A live run of this platform came up perfectly and could not be entered. The
administrator token it printed had been generated by ``secrets.token_urlsafe``
and written into the environment; the running gateway resolved bearer tokens
through the identity store, which had never heard of it. Two sources of truth
about one credential, and the one the operator was given was the wrong one.

So there is one source here, and it is the identity system. The bootstrap
credential is issued by ``TokenService.issue`` against a principal that exists
in the store with a grant that exists in the store, exactly like every other
token this platform serves. It is not a bypass, not a magic header, not a
gateway special case. What makes it a *bootstrap* credential is only that it is
short and narrow:

**Short.** One hour. It is the only credential in the system whose life is
measured in seconds, which is why the token service had to learn a sub-day
lifetime for it rather than the other way round.

**Narrow.** Two permissions: see who you are, and mint a token. The principal
behind it is an owner — it has to be, or the durable credential it establishes
could not be granted anything — but the token itself is ceilinged, so a leaked
bootstrap credential cannot change a configuration or execute a remediation.

**Spent.** Establishing a durable credential revokes it in the same transaction
that issues the replacement, and deletes the file it was delivered in. An hour
is a bound, not a plan.

**Delivered to a file.** The one edge case that decided this: an operator who
closed the terminal before reading the token has not lost their deployment. The
file is written 0600 and is the *copy* — the store is the record. When the two
disagree, the store wins, because a restored backup would otherwise leave a file
nobody can sign in with and no way to tell.
"""

from __future__ import annotations

